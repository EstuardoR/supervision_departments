    /** Trae el historial de la supervisión y llena la tabla, de más antiguo a más reciente. */
    private void cargarHistorial(int idSupervision) {
        try {
            java.util.List<model.HistorialSupervision> historial =
                    new controller.BandejaPlanificacionController().obtenerHistorial(idSupervision);
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblHistorial.getModel();
            modelo.setRowCount(0);
            for (model.HistorialSupervision h : historial) {
                modelo.addRow(new Object[]{
                    h.getEstado(),
                    h.getFechaHora() != null ? FORMATO_FECHA.format(h.getFechaHora()) : "",
                    h.getObservaciones(),
                    h.getResponsableNombre()
                });
            }
        } catch (controller.BandejaPlanificacionException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

